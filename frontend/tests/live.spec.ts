import { test, expect } from '@playwright/test';

test('реальный стек: регистрация, каталог, бронь и нейросетевая подборка', async ({ page, request }) => {
  test.skip(!process.env.E2E_ADMIN_EMAIL || !process.env.E2E_ADMIN_PASSWORD, 'Set test administrator credentials on an isolated stack');
  const login = await request.post('/auth/login', { data: { email: process.env.E2E_ADMIN_EMAIL, password: process.env.E2E_ADMIN_PASSWORD } });
  expect(login.ok()).toBeTruthy();
  const { access_token } = await login.json();
  const headers = { Authorization: `Bearer ${access_token}` };
  const suffix = `${Date.now()}-${Math.random().toString(16).slice(2)}`;
  const created = await request.post('/catalog/books', { headers, data: { title: `Космос ${suffix}`, description: 'Научная фантастика о путешествиях, звёздах и дружбе', author_ids: [], genre_ids: [] } });
  expect(created.status()).toBe(201);
  const book = await created.json();
  const copy = await request.post('/circulation/copies', { headers, data: { book_id: book.id, barcode: `E2E-${suffix}` } });
  expect(copy.status()).toBe(201);
  const indexed = await request.post('/recommendations/reindex', { headers, timeout: 300000 });
  expect(indexed.ok()).toBeTruthy();
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Каталог книг' })).toBeVisible();
  await page.getByRole('textbox', { name: 'Поиск книг' }).fill(book.title);
  await page.getByRole('button', { name: 'Найти', exact: true }).click();
  await expect(page.getByRole('button', { name: `Подробнее: ${book.title}` })).toBeVisible();
  await page.getByRole('button', { name: 'Регистрация', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Электронная почта').fill(`e2e-${suffix}@example.com`);
  await dialog.getByLabel('Пароль', { exact: true }).fill('E2e-password-123!');
  await dialog.getByLabel('Повторите пароль').fill('E2e-password-123!');
  await dialog.getByRole('button', { name: 'Создать аккаунт' }).click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button', { name: `Подробнее: ${book.title}` }).click();
  await expect(page.getByRole('dialog').getByText('Доступно на выбранные даты: 1')).toBeVisible();
  await page.getByRole('button', { name: 'Забронировать книгу', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Личный кабинет' })).toBeVisible();
  await expect(page.locator('.booking-list').getByRole('heading', { name: book.title, exact: true })).toBeVisible();
  await page.getByLabel('Ваши читательские интересы').fill('фантастика о космосе');
  await expect(page.getByRole('button', { name: 'Подобрать книги' })).toBeEnabled({ timeout: 300000 });
  const neuralResponse = page.waitForResponse(r => r.url().includes('/recommendations/me?') && r.request().method() === 'GET');
  await page.getByRole('button', { name: 'Подобрать книги' }).click();
  const response = await neuralResponse;
  expect(response.ok()).toBeTruthy();
  const results = await response.json();
  expect(results.basis).toBe('interests');
  expect(results.items.length).toBeGreaterThan(0);
  expect(results.items.every((r: { score: number }) => typeof r.score === 'number')).toBeTruthy();
  await expect(page.getByText('Подбор для вас', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Отменить бронь', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Отменить бронирование', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Время для новой истории' })).toBeVisible();
});
